<h2>3. Sizin yüklediğiniz üçüncü kişi verileri</h2>
<p>LUNAHAN uygulamasına <strong>sizin girdiğiniz</strong> müşteri, tedarikçi ve çalışan verileri bakımından veri sorumlusu sizsiniz; Lunify bu verileri yalnızca hizmeti sunmak amacıyla, talimatınız doğrultusunda <strong>veri işleyen</strong> olarak işler. Bu veriler başka müşterilerle paylaşılmaz, satılmaz ve yapay zekâ modeli eğitmek için kullanılmaz.</p>

<h2>4. Verilerin aktarıldığı taraflar</h2>
<ul>
<li><strong>Barındırma:</strong> Avrupa Birliği (Almanya) içindeki veri merkezi sağlayıcısı.</li>
<li><strong>Yapay zekâ sağlayıcıları:</strong> Yalnızca AI özelliklerini kullandığınızda ilgili istem içeriği API üzerinden model sağlayıcısına (ör. DeepSeek, OpenRouter üzerinden seçilen modeller) iletilir. Sağlayıcılar, içeriği model eğitimi için kullanmama taahhüdüyle seçilir.</li>
<li><strong>E-posta ve entegrasyon servisleri:</strong> Google/Gmail API, SMTP, Brevo ve WhatsApp/Meta — yalnızca <em>sizin bağladığınız</em> hesaplar için ve yalnızca o hesabın verisiyle.</li>
<li><strong>Yetkili kamu kurumları:</strong> hukuki yükümlülük halinde.</li>
</ul>
<p>Yurt dışına aktarım, KVKK m.9 kapsamında açık rıza veya uygun güvenceler (standart sözleşme hükümleri) ile yapılır.</p>

<h2>5. Saklama ve silme süreleri</h2>
<ul>
<li>Hesabınız aktif olduğu sürece saklanır; hesap kapatıldıktan sonra <strong>en fazla 90 gün</strong> içinde silinir veya anonim hale getirilir.</li>
<li>Sistem güvenlik ve erişim logları en fazla <strong>12 ay</strong> tutulur.</li>
<li>Mali kayıtlar mevzuat gereği <strong>10 yıl</strong> saklanır.</li>
<li>Günlük yedekler döngüsel olarak üzerine yazılır; silme talebiniz yedek döngüsü tamamlandığında yedeklerde de etkisini gösterir.</li>
<li>Bağladığınız Google/WhatsApp hesabının bağlantısını kaldırdığınızda ilgili erişim anahtarları uygulamadan silinir.</li>
</ul>

<h2>6. Haklarınız (KVKK m.11) ve başvuru</h2>
<p>Kişisel verilerinizin işlenip işlenmediğini öğrenme, bilgi talep etme, aktarıldığı tarafları bilme, düzeltme, silme veya yok edilmesini isteme, işlemenin sınırlandırılmasını ve zararınızın giderilmesini talep etme haklarına sahipsiniz.</p>
<div class="card"><p style="margin:0"><strong>Başvuru:</strong> <a href="mailto:info@lunify.world?subject=KVKK%20Ba%C5%9Fvurusu%20-%20LUNAHAN">info@lunify.world</a> adresine “KVKK Başvurusu” konusuyla yazın. Başvurunuz en geç <strong>30 gün</strong> içinde ücretsiz yanıtlanır. Verilerinizin dışa aktarımını veya silinmesini aynı adresten “Veri Silme Talebi” konusuyla talep edebilirsiniz.</p></div>

<h2>7. Güvenlik önlemleri</h2>
<ul>
<li>Her hesap için izole veri alanı; sorgular oturum sahibinin kimliğiyle sınırlandırılır.</li>
<li>Sunucu tarafında doğrulanan oturumlar; oturum çerezleri <code>HttpOnly</code>, <code>Secure</code> ve <code>SameSite</code> işaretli.</li>
<li>Yüklenen dosyalar web kökü dışından/erişimi kapalı dizinden, yalnızca sahiplik kontrolünden sonra sunulur.</li>
<li>Tüm trafik HTTPS/TLS ile şifrelenir (HTTP → HTTPS yönlendirme, HSTS); şifreler geri döndürülemez şekilde saklanır.</li>
<li>Günlük otomatik yedekleme, erişim logları, güvenlik duvarı ve brüt kuvvet koruması (fail2ban).</li>
</ul>

